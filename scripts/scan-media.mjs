// Lists every file in public/media so components know which real assets exist,
// and makes 1200x630 JPEG share images for products (public/media/og/<slug>.jpg),
// since some apps (WhatsApp among them) don't show WebP link previews.
// Runs automatically before `npm run dev` and `npm run build`; run `npm run media`
// after dropping in new files while the dev server is running.
import { readdirSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "public", "media");
if (!existsSync(root)) mkdirSync(root, { recursive: true });

function list() {
  const files = [];
  (function walk(dir) {
    for (const name of readdirSync(dir)) {
      if (name.startsWith(".") || name === "README.md") continue;
      const full = join(dir, name);
      if (statSync(full).isDirectory()) walk(full);
      else files.push(relative(root, full).split(sep).join("/").toLowerCase());
    }
  })(root);
  return files.sort();
}

// Share images. sharp ships with Next.js; if it can't load, skip quietly.
async function makeShareImages(files) {
  let sharp;
  try {
    sharp = (await import("sharp")).default;
  } catch {
    return 0;
  }
  const PARCHMENT = { r: 238, g: 226, b: 203 };
  const ogDir = join(root, "og");
  if (!existsSync(ogDir)) mkdirSync(ogDir);
  let made = 0;
  for (const f of files) {
    const m = f.match(/^products\/(.+?)(-cutout)?\.(webp|jpe?g|png|avif)$/);
    if (!m) continue;
    const [, slug, cutout] = m;
    // A cut-out wins over a styled photo, as on the site.
    if (!cutout && files.some((x) => x.startsWith(`products/${slug}-cutout.`))) continue;
    const src = join(root, f);
    const out = join(ogDir, `${slug}.jpg`);
    if (existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs) continue;
    const img = cutout
      ? sharp({ create: { width: 1200, height: 630, channels: 3, background: PARCHMENT } }).composite([
          { input: await sharp(src).resize(1000, 520, { fit: "inside" }).toBuffer(), gravity: "center" },
        ])
      : sharp(src).resize(1200, 630, { fit: "cover", position: "attention" });
    await img.jpeg({ quality: 84, progressive: true }).toFile(out);
    made++;
  }
  return made;
}

const made = await makeShareImages(list());
const files = list();
const out = `// Generated by scripts/scan-media.mjs. Do not edit by hand.\nexport const MEDIA_FILES: readonly string[] = ${JSON.stringify(files, null, 2)};\n`;
writeFileSync(join(process.cwd(), "src", "lib", "media-manifest.ts"), out);
console.log(`media: ${files.length} file(s) in public/media${made ? `, ${made} share image(s) made` : ""}`);
