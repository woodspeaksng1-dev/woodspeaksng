// Generates the preloader wordmark paths from a calligraphy font.
// Run: node scripts/generate-wordmark.mjs
// Replace with the client's own wordmark SVG paths when it arrives.
import opentypeModule from 'opentype.js';
const opentype = opentypeModule.parse ? opentypeModule : opentypeModule.default;
import fs from 'node:fs';

const WORD = 'Woodspeaks';
const fontBuf = fs.readFileSync(new URL('./pinyon-script-latin-400-normal.woff', import.meta.url));
const font = opentype.parse(fontBuf.buffer.slice(fontBuf.byteOffset, fontBuf.byteOffset + fontBuf.byteLength));
const SIZE = 120;
const glyphPaths = font.getPaths(WORD, 0, SIZE, SIZE);

let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const p of glyphPaths) {
  const b = p.getBoundingBox();
  minX = Math.min(minX, b.x1); minY = Math.min(minY, b.y1);
  maxX = Math.max(maxX, b.x2); maxY = Math.max(maxY, b.y2);
}
const pad = 8;
const r = (n) => Math.round(n * 10) / 10;

// Split each glyph into contours (one per "M") so the pen traces them in order.
const contours = [];
for (const p of glyphPaths) {
  let cur = [];
  const flush = () => { if (cur.length) contours.push(cur.join('')); cur = []; };
  for (const c of p.commands) {
    if (c.type === 'M') { flush(); cur.push(`M${r(c.x)} ${r(c.y)}`); }
    else if (c.type === 'L') cur.push(`L${r(c.x)} ${r(c.y)}`);
    else if (c.type === 'Q') cur.push(`Q${r(c.x1)} ${r(c.y1)} ${r(c.x)} ${r(c.y)}`);
    else if (c.type === 'C') cur.push(`C${r(c.x1)} ${r(c.y1)} ${r(c.x2)} ${r(c.y2)} ${r(c.x)} ${r(c.y)}`);
    else if (c.type === 'Z') cur.push('Z');
  }
  flush();
}

const out = `// Generated by scripts/generate-wordmark.mjs — do not edit by hand.
export const WORDMARK = {
  viewBox: "${r(minX - pad)} ${r(minY - pad)} ${r(maxX - minX + pad * 2)} ${r(maxY - minY + pad * 2)}",
  contours: ${JSON.stringify(contours)},
} as const;
`;
fs.writeFileSync(new URL('../src/components/preloader/wordmark-data.ts', import.meta.url), out);
console.log('contours:', contours.length, 'bytes:', out.length);
